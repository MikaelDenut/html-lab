function inner(style, name) {
  const file = join(assets, style, `${name}-${style}.svg`);
  const svg = readFileSync(file, 'utf8');
  const m = svg.match(/<svg[^>]*>([\s\S]*)<\/svg>/);
  if (!m) throw new Error(`Not an SVG: ${file}`);
  return m[1].trim();
}

function symbol(id, body) {
  return `<symbol id="i-${id}" viewBox="0 0 256 256" fill="currentColor">${body}</symbol>`;
}

function alias(id, target) {
  return `<symbol id="i-${id}" viewBox="0 0 256 256"><use href="#i-${target}"/></symbol>`;
}

const names = [...new Set([...Object.values(BOARD_WORDS), ...UI_ICONS])];
const parts = [APP_ICON];
for (const name of names) {
  parts.push(symbol(name, inner('duotone', name)));
  parts.push(symbol(`${name}-bold`, inner('bold', name)));
}
for (const [word, target] of Object.entries(BOARD_WORDS)) {
  parts.push(alias(word, target));
  parts.push(alias(`${word}-bold`, `${target}-bold`));
}

const sprite = '<svg xmlns="http://www.w3.org/2000/svg" id="icon-sprite" aria-hidden="true"'
  + ' style="position:absolute;width:0;height:0;overflow:hidden">'
  + parts.join('')
  + '</svg>';

const js = `// Generated by scripts/build-icons.mjs. Do not edit by hand.
const SPRITE = ${JSON.stringify(sprite)};

// Inserts the sprite once, at the top of the body.
export function installSprite() {
  if (document.getElementById('icon-sprite')) return;
  document.body.insertAdjacentHTML('afterbegin', SPRITE);
}
`;

writeFileSync(outFile, js);
console.log(`ui/icons.js: ${names.length} icons, ${(js.length / 1024).toFixed(1)} KB`);
